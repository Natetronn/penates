#!/usr/bin/env python3
"""Write ui/credits.js: every open-source crate Penates is built from (on any platform), with its version,
license and source, for the Credits page in the manager's About dialog.

    python3 scripts/gen-credits.py          # after changing dependencies (Cargo.lock)
    python3 scripts/gen-credits.py --check  # fail if ui/credits.js is out of date (CI)
"""
import json, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "ui" / "credits.js"


def components():
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT,
                                     check=True, capture_output=True, text=True).stdout)
    ours = set(meta["workspace_members"])
    seen, out = set(), []
    for p in sorted(meta["packages"], key=lambda p: (p["name"].lower(), p["version"])):
        if p["id"] in ours or (p["name"], p["version"]) in seen:
            continue
        seen.add((p["name"], p["version"]))
        out.append([p["name"], p["version"], p.get("license") or "see source", p.get("repository") or ""])
    return out


def render(items):
    rows = ",\n".join("  " + json.dumps(i, ensure_ascii=False) for i in items)
    return ("// Generated by scripts/gen-credits.py from Cargo.lock; do not edit.\n"
            "// [name, version, license, source]\n"
            f"window.PENATES_CREDITS = [\n{rows}\n];\n")


def main():
    text = render(components())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("ui/credits.js is out of date: run python3 scripts/gen-credits.py and commit it")
        print("ui/credits.js is current")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10)) - 4} components)")


if __name__ == "__main__":
    main()
